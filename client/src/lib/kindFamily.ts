const FAMILY_OF = new Map<number, KindFamily>();
for (const [family, kinds] of Object.entries(FAMILIES) as [KindFamily, readonly number[]][])
  for (const kind of kinds) FAMILY_OF.set(kind, family);

/** The family a kind belongs to, or null for a kind no one has named. */
export function kindFamily(kind: number): KindFamily | null {
  return FAMILY_OF.get(kind) ?? null;
}

/** The pill's tint per family: one hue each, so a scan down a mixed list reads by colour. */
const FAMILY_TONE: Record<KindFamily, Tone> = {
  people: "violet",
  note: "blue",
  social: "indigo",
  article: "amber",
  media: "fuchsia",
  code: "emerald",
  live: "red",
  market: "teal",
  apps: "sky",
  record: "orange",
  list: "rose",
};

export function kindTone(kind: number): Tone {
  const family = kindFamily(kind);
  return family ? FAMILY_TONE[family] : "slate";
}
